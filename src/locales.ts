const singleMapCountEn = {
  chapters: '1 chapter',
  articlesCount: '1 article',
  sectionsCount: '1 section',
  paragraphCount: '1 para.',
};

export function mapCountLabel(
  language: string,
  count: number,
  unit: keyof typeof singleMapCountEn,
) {
  const copy = language.startsWith('zh') ? zh : en;
  if (copy === en && count === 1) return singleMapCountEn[unit];
  return unit === 'paragraphCount'
    ? copy.paragraphCount.replace('{n}', String(count))
    : `${count} ${copy[unit]}`;
}

